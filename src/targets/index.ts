const byId = new Map(TARGETS.map((t) => [t.id, t]))

export function getTarget(id: string): TargetSpec {
  return byId.get(id) ?? byId.get('custom/custom')!
}

export function getStore(id: StoreId): StoreInfo {
  return STORES.find((s) => s.id === id) ?? STORES[STORES.length - 1]
}

export function targetsForStore(store: StoreId): TargetSpec[] {
  return TARGETS.filter((t) => t.store === store)
}

export function targetLabel(id: string): string {
  const t = getTarget(id)
  return t.store === 'custom' ? t.label : `${getStore(t.store).name} · ${t.label}`
}

export function staleTargets(maxAgeDays = 180, now = Date.now()): TargetSpec[] {
  return TARGETS.filter((t) => now - Date.parse(t.verifiedAt) > maxAgeDays * 86_400_000)
}
